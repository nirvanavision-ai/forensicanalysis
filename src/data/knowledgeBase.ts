/**
 * Concept cards for the Knowledge Base tab.
 *
 * The analysis engine may refer to frameworks ONLY by these ids. The app renders the
 * definitions and sources from this curated file, so an analysis cannot invent a citation.
 */

import { mergeResearchConcepts } from './research';

export type EvidenceKind = 'empirical' | 'theory' | 'clinical' | 'practitioner' | 'popular' | 'logic';

export const EVIDENCE_KIND_LABEL: Record<EvidenceKind, string> = {
  empirical: 'Empirical research',
  theory: 'Theoretical explanation',
  clinical: 'Clinical formulation',
  practitioner: 'Practitioner technique',
  popular: 'Popular / community model',
  logic: 'Logic & argumentation standard',
};

export const EVIDENCE_KIND_HELP: Record<EvidenceKind, string> = {
  empirical: 'Supported by systematic studies. Studies describe groups and tendencies, not the people in your transcript.',
  theory: 'An explanatory framework. Useful for generating hypotheses; it does not prove what any person was thinking.',
  clinical: 'A formulation from clinical practice. Not something that can be diagnosed from a transcript.',
  practitioner: 'A technique developed in practice (negotiation, communication). Judged by usefulness, not proof.',
  popular: 'A widely used interpretive model or community concept with limited formal research behind it.',
  logic: 'A standard for evaluating reasoning. It tells you whether a conclusion follows, not whether premises are true.',
};

export interface Concept {
  id: string;
  title: string;
  domain: string;
  kind: EvidenceKind;
  definition: string;
  application: string;
  limitations: string;
  lookFor: string[];
  sources: string[];
  /** Bandura's loci, used for the moral disengagement map. */
  locus?: 'conduct' | 'agency' | 'outcomes' | 'recipient';
  /** From the research pass: short summaries of what recent evidence shows. */
  researchNotes?: string[];
  /** From the research pass: what this concept cannot establish about anyone in a transcript. */
  cannotEstablish?: string[];
  /** From the research pass: Strong / Moderate / Tentative support for the concept itself. */
  researchConfidence?: string;
  /** The concept is contested in the research literature. */
  contested?: boolean;
  /** Terms to keep out of findings (they may appear in the card itself). */
  avoidTerms?: string[];
}

